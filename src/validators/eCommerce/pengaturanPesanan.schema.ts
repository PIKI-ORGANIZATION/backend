import { z } from "zod";

////////////////////////////////////////////////////
// STRUCTURE PAJAK
////////////////////////////////////////////////////
const pajakItemSchema = z.object({
  nama: z.string().min(1),
  rasio: z.number().min(0),
});

////////////////////////////////////////////////////
// BASE SCHEMA
////////////////////////////////////////////////////
const basePengaturanPesananSchema = z.object({
  pajakPesanan: z.array(pajakItemSchema).min(1),

  pajakProdukPesanan: z.array(pajakItemSchema).optional(),
});

////////////////////////////////////////////////////
// CREATE
////////////////////////////////////////////////////
export const createPengaturanPesananSchema = basePengaturanPesananSchema;

////////////////////////////////////////////////////
// UPDATE
////////////////////////////////////////////////////
export const updatePengaturanPesananSchema =
  basePengaturanPesananSchema.partial();
